// 依燈號（橘燈再依類型）取得說法；橘燈尚未選類型時回傳 null
export function getLightScript(light, orangeType) {
  if (light === "orange") return LIGHT_SCRIPTS[orangeType] ?? null;
  return LIGHT_SCRIPTS[light] ?? null;
}

export function getQ11Ask(itemLabel) {
  return Q11_GUIDE.ask.replace("{item}", itemLabel);
}
